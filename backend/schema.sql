-- =====================================================================
-- 校园好物市集 · 数据库结构（H2 2.x）
--
-- 唯一 SQL 源文件：位于 backend/ 根目录（题目 §1 目录要求），
-- 由 Maven resources 复制到 classpath，应用通过 classpath:schema.sql 加载。
--
-- 建表顺序遵循依赖方向：products -> orders -> payments
-- 删除顺序相反，保证重复初始化幂等。
--
-- 注意：DROP TABLE 仅适用于本项目的一次性内存库（每次上下文启动重建），
--       不是通用迁移方案，不可用于文件库 / 共享库 / 生产环境。
-- =====================================================================

DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;

-- ---------------------------------------------------------------------
-- 商品
-- ---------------------------------------------------------------------
CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(50)   NOT NULL,
    price       BIGINT        NOT NULL,                        -- 单位：分
    stock       INT           NOT NULL,
    category    VARCHAR(32)   NOT NULL,                        -- 不限定枚举，仅非空 + 长度
    description VARCHAR(200),                                  -- 可选
    status      VARCHAR(16)   NOT NULL DEFAULT 'on',           -- 题目 §4 L0-5：仅 on / off
    seller_name VARCHAR(64)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_products_price_positive CHECK (price > 0),
    CONSTRAINT ck_products_stock_nonneg   CHECK (stock >= 0),
    CONSTRAINT ck_products_status         CHECK (status IN ('on', 'off'))
);

-- ---------------------------------------------------------------------
-- 订单
--
-- product_title / unit_price / total_amount 是下单时点的商品快照：
-- 题目 §5 L1-6 要求由服务端按数据库价格计算并落库，
-- 保证后续商品改名或改价不影响历史订单。
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(64)   NOT NULL,                      -- 日期 + UUID，题目 §5 要求唯一
    product_id    BIGINT        NOT NULL,
    product_title VARCHAR(50)   NOT NULL,                      -- 快照
    quantity      INT           NOT NULL,
    unit_price    BIGINT        NOT NULL,                      -- 快照，单位：分
    total_amount  BIGINT        NOT NULL,                      -- 快照，单位：分
    buyer_name    VARCHAR(64)   NOT NULL,
    buyer_phone   VARCHAR(20)   NOT NULL,
    address       VARCHAR(255)  NOT NULL,
    status        VARCHAR(16)   NOT NULL DEFAULT 'created',    -- 题目 §5 created / §6 paid
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP,                                   -- 支付成功时写入

    CONSTRAINT uk_orders_order_no   UNIQUE (order_no),
    CONSTRAINT ck_orders_quantity   CHECK (quantity >= 1),
    CONSTRAINT ck_orders_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_orders_total      CHECK (total_amount > 0),
    CONSTRAINT ck_orders_amount     CHECK (total_amount = unit_price * quantity),
    CONSTRAINT ck_orders_status     CHECK (status IN ('created', 'paid')),
    CONSTRAINT ck_orders_paid_at    CHECK ((status = 'paid') = (paid_at IS NOT NULL)),
    CONSTRAINT fk_orders_product    FOREIGN KEY (product_id) REFERENCES products (id)
);

-- ---------------------------------------------------------------------
-- 支付
--
-- order_no 唯一是支付幂等的数据库兜底（题目 §6 L2-9）：
-- 应用层用条件 UPDATE 抢占状态迁移，DB 唯一约束杜绝「两条成功记录」。
-- 本项目同步返回 paid，无中间态，故 status 仅允许 'paid'。
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(64) NOT NULL,
    order_no   VARCHAR(64) NOT NULL,
    amount     BIGINT      NOT NULL,                           -- 单位：分
    method     VARCHAR(16) NOT NULL,                           -- 题目 §6：alipay / wechat
    status     VARCHAR(16) NOT NULL DEFAULT 'paid',
    paid_at    TIMESTAMP   NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_payments_payment_id UNIQUE (payment_id),
    CONSTRAINT uk_payments_order_no   UNIQUE (order_no),
    CONSTRAINT ck_payments_amount     CHECK (amount > 0),
    CONSTRAINT ck_payments_method     CHECK (method IN ('alipay', 'wechat')),
    CONSTRAINT ck_payments_status     CHECK (status IN ('paid')),
    CONSTRAINT fk_payments_order      FOREIGN KEY (order_no) REFERENCES orders (order_no)
);

-- ---------------------------------------------------------------------
-- 索引
--
-- 支撑题目 §5 L1-8：按 buyerPhone 查询订单列表、按创建时间倒序。
-- created_at 在同一毫秒可能并列，业务层排序会追加 id DESC 保证确定性；
-- 因此第三列把 id DESC 也放进索引，让索引序 = 查询序（created_at DESC, id DESC），
-- 分页时可以沿索引顺序直接取前 N 条（L2-13 专项，详见 DESIGN.md 附录 A）。
--
-- 暂不建立：
--   products.title        —— L0-3 keyword 为 LIKE '%kw%'，B-tree 索引无效
--   products(category)    —— 数据量小，内存库全表扫描开销可忽略
-- ---------------------------------------------------------------------
CREATE INDEX idx_orders_buyer_phone_created
    ON orders (buyer_phone, created_at DESC, id DESC);
