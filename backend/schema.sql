-- 金额溢出处理约定（应用层为主，数据库兜底）：
--   1. 服务端统一 Math.multiplyExact(unitPrice, quantity) 计算总金额
--   2. 溢出抛 ArithmeticException → 事务回滚 → 统一响应 50000
--   3. 兜底：H2 BIGINT 乘法溢出直接报错 + chk_orders_amount_calc 不变量，
--      溢出/截断值不可能落库，只会导致下单失败
