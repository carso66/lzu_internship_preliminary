-- 校园好物市集：初始数据库结构
--
-- 所有金额单位为“分”，使用 BIGINT。
-- 时间字段保留时区；应用统一按 UTC 写入和输出。
--
-- 本文件是当前完整结构快照（V1 基线 + 后续迁移）。
-- 应用启动只运行 Flyway，不通过 Spring SQL 初始化执行本文件。
-- 后续数据库变更通过新增迁移维护；V1 已应用后不要再修改其内容。
--
-- 本脚本用于空数据库初始化，不重复执行，不清理已有数据。


CREATE TABLE products (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title        VARCHAR(120) NOT NULL,
    price        BIGINT NOT NULL,
    stock        INTEGER NOT NULL,
    category     VARCHAR(50) NOT NULL,
    description  VARCHAR(2000),
    status       VARCHAR(10) NOT NULL DEFAULT 'on',
    seller_name  VARCHAR(100) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE
                 NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_products
        PRIMARY KEY (id),

    CONSTRAINT ck_products_title_nonblank
        CHECK (CHAR_LENGTH(TRIM(title)) > 0),

    CONSTRAINT ck_products_price
        CHECK (price >= 0),

    CONSTRAINT ck_products_stock
        CHECK (stock >= 0),

    CONSTRAINT ck_products_category_nonblank
        CHECK (CHAR_LENGTH(TRIM(category)) > 0),

    CONSTRAINT ck_products_status
        CHECK (status IN ('on', 'off')),

    CONSTRAINT ck_products_seller_name_nonblank
        CHECK (CHAR_LENGTH(TRIM(seller_name)) > 0)
);

CREATE INDEX idx_products_created_id
    ON products (created_at DESC, id DESC);

CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_no      VARCHAR(64) NOT NULL,
    product_id    BIGINT NOT NULL,
    product_title VARCHAR(120) NOT NULL,
    quantity      INTEGER NOT NULL,
    unit_price    BIGINT NOT NULL,
    total_amount  BIGINT NOT NULL,
    buyer_name    VARCHAR(100) NOT NULL,
    buyer_phone   VARCHAR(20) NOT NULL,
    address       VARCHAR(500) NOT NULL,
    status        VARCHAR(16) NOT NULL DEFAULT 'created',
    created_at    TIMESTAMP WITH TIME ZONE
                  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_orders
        PRIMARY KEY (id),

    CONSTRAINT uk_orders_order_no
        UNIQUE (order_no),

    CONSTRAINT fk_orders_product
        FOREIGN KEY (product_id) REFERENCES products (id),

    CONSTRAINT ck_orders_order_no_nonblank
        CHECK (CHAR_LENGTH(TRIM(order_no)) > 0),

    CONSTRAINT ck_orders_product_title_nonblank
        CHECK (CHAR_LENGTH(TRIM(product_title)) > 0),

    CONSTRAINT ck_orders_quantity
        CHECK (quantity >= 1),

    CONSTRAINT ck_orders_unit_price
        CHECK (unit_price >= 0),

    CONSTRAINT ck_orders_total_amount
        CHECK (total_amount >= 0),

    CONSTRAINT ck_orders_amount_calculation
        CHECK (
            CAST(total_amount AS DECIMAL(38, 0))
            = CAST(unit_price AS DECIMAL(38, 0)) * quantity
        ),

    CONSTRAINT ck_orders_buyer_name_nonblank
        CHECK (CHAR_LENGTH(TRIM(buyer_name)) > 0),

    CONSTRAINT ck_orders_buyer_phone_nonblank
        CHECK (CHAR_LENGTH(TRIM(buyer_phone)) > 0),

    CONSTRAINT ck_orders_address_nonblank
        CHECK (CHAR_LENGTH(TRIM(address)) > 0),

    CONSTRAINT ck_orders_status
        CHECK (status IN ('created', 'paid')),

    CONSTRAINT ck_orders_status_paid_at
        CHECK (
            (status = 'created' AND paid_at IS NULL)
            OR
            (status = 'paid' AND paid_at IS NOT NULL)
        )
);

CREATE INDEX idx_orders_buyer_created_id
    ON orders (buyer_phone, created_at DESC, id DESC);


CREATE TABLE payments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_no  VARCHAR(64) NOT NULL,
    order_no    VARCHAR(64) NOT NULL,
    amount      BIGINT NOT NULL,
    method      VARCHAR(16) NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'paid',
    paid_at     TIMESTAMP WITH TIME ZONE
                NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payments
        PRIMARY KEY (id),

    CONSTRAINT uk_payments_payment_no
        UNIQUE (payment_no),

    -- 一个订单最多一条成功支付记录。
    CONSTRAINT uk_payments_order_no
        UNIQUE (order_no),

    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_no) REFERENCES orders (order_no),

    CONSTRAINT ck_payments_payment_no_nonblank
        CHECK (CHAR_LENGTH(TRIM(payment_no)) > 0),

    CONSTRAINT ck_payments_amount
        CHECK (amount >= 0),

    CONSTRAINT ck_payments_method
        CHECK (method IN ('alipay', 'wechat')),

    CONSTRAINT ck_payments_status
        CHECK (status = 'paid')
);


-- V2：订单号序列。全局递增，回滚会产生空洞，但保证并发下不重复。
CREATE SEQUENCE order_no_seq START WITH 1 INCREMENT BY 1;

-- V3：支付编号序列。回滚会产生空洞，但保证并发下不重复。
CREATE SEQUENCE payment_no_seq START WITH 1 INCREMENT BY 1;
