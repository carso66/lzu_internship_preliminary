-- =============================================================
-- 校园好物市集 · 数据库结构（H2 2.x，DDL 基本兼容 PostgreSQL）
-- 约定：
--   · 金额一律用整数「分」存储（INT），不使用 DECIMAL / FLOAT
--   · 时间由数据库 DEFAULT CURRENT_TIMESTAMP 写入，接口层格式化为 ISO-8601
--   · 本脚本可重复执行（先 DROP 再建），用于初始化或重置库
-- 加载：
--   java -cp h2.jar org.h2.tools.RunScript -url jdbc:h2:./data/market -user sa -script schema.sql
--   Spring Boot: spring.sql.init.mode=always
--                spring.sql.init.schema-locations=file:./schema.sql
-- =============================================================

-- 依赖顺序：payments -> orders -> products
DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;

-- -------------------------------------------------------------
-- 商品
--   status: on 在售 / off 已下架（下架后不可下单，但仍可在列表里查到）
--   category 不建字典表/外键：接口允许传任意分类字符串，前端下拉只是推荐值
--   updated_at 由应用层在执行 UPDATE 时一并刷新
-- -------------------------------------------------------------
CREATE TABLE products (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(50)  NOT NULL,
    price       INT          NOT NULL,
    stock       INT          NOT NULL DEFAULT 0,
    category    VARCHAR(16)  NOT NULL,
    description VARCHAR(200),
    status      VARCHAR(8)   NOT NULL DEFAULT 'on',
    seller_name VARCHAR(64)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_products_price  CHECK (price > 0),
    CONSTRAINT ck_products_stock  CHECK (stock >= 0),
    CONSTRAINT ck_products_status CHECK (status IN ('on', 'off'))
);

-- 列表页主路径：status 过滤 + created_at 倒序 + 分页
CREATE INDEX idx_products_status_created ON products (status, created_at DESC);
-- category 过滤（常与 status 叠加；两列组合索引收益有限，单列更通用）
CREATE INDEX idx_products_category       ON products (category);
-- 标题模糊匹配 LIKE '%x%' 无法走索引，此索引服务前缀检索与排序
CREATE INDEX idx_products_title          ON products (title);

-- -------------------------------------------------------------
-- 订单
--   product_title / unit_price 是下单时的快照：商品日后改名改价不影响历史订单
--   total_amount 由服务端 unit_price * quantity 计算，不接受客户端传值
--   status: created / paid —— 不设 CHECK 枚举，便于后续扩展 cancelled / refunded
-- -------------------------------------------------------------
CREATE TABLE orders (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(32)  NOT NULL,
    product_id    BIGINT       NOT NULL,
    product_title VARCHAR(50)  NOT NULL,
    quantity      INT          NOT NULL,
    unit_price    INT          NOT NULL,
    total_amount  INT          NOT NULL,
    buyer_name    VARCHAR(50)  NOT NULL,
    buyer_phone   VARCHAR(20)  NOT NULL,
    address       VARCHAR(255) NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'created',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP,
    CONSTRAINT uk_orders_order_no   UNIQUE (order_no),
    CONSTRAINT ck_orders_quantity   CHECK (quantity >= 1),
    CONSTRAINT ck_orders_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_orders_total      CHECK (total_amount >= 0),
    -- 下单事务用条件更新扣库存，外键再兜住脏 product_id
    CONSTRAINT fk_orders_product    FOREIGN KEY (product_id) REFERENCES products (id)
);

-- 订单列表：按手机号过滤 + 创建时间倒序分页
CREATE INDEX idx_orders_phone_created ON orders (buyer_phone, created_at DESC);

-- -------------------------------------------------------------
-- 支付单
--   payment_id 即对外返回的业务号（PAY...），直接作主键
--   uk_payments_order_id：一个订单最多一条支付记录，用唯一约束兜住并发重复支付
--     （同步返回 paid 的简化链路下，"处理中"记录也占住该订单；
--       若改为异步回调 + 失败重试，应改成只对 status='paid' 建唯一约束）
-- -------------------------------------------------------------
CREATE TABLE payments (
    payment_id VARCHAR(32)  PRIMARY KEY,
    order_id   BIGINT       NOT NULL,
    order_no   VARCHAR(32)  NOT NULL,
    amount     INT          NOT NULL,
    method     VARCHAR(16)  NOT NULL,
    status     VARCHAR(16)  NOT NULL DEFAULT 'processing',
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at    TIMESTAMP,
    CONSTRAINT uk_payments_order_id UNIQUE (order_id),
    CONSTRAINT ck_payments_amount   CHECK (amount >= 0),
    CONSTRAINT ck_payments_method   CHECK (method IN ('alipay', 'wechat')),
    CONSTRAINT fk_payments_order    FOREIGN KEY (order_id) REFERENCES orders (id)
);

-- 支付单按订单号回查（重复支付返回 40903 时要定位已有支付）
CREATE INDEX idx_payments_order_no ON payments (order_no);
