-- 商品表
CREATE TABLE IF NOT EXISTS products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(100)  NOT NULL,
    description VARCHAR(500),
    category    VARCHAR(50)   NOT NULL,
    price       INT           NOT NULL,               -- 单价，单位：分
    stock       INT           NOT NULL DEFAULT 0,     -- 库存
    status      VARCHAR(10)   NOT NULL DEFAULT 'on',  -- 'on' 在售 / 'off' 下架
    seller_name VARCHAR(100),
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_products_price  CHECK (price >= 0),
    CONSTRAINT chk_products_stock  CHECK (stock >= 0),
    CONSTRAINT chk_products_status CHECK (status IN ('on', 'off'))
);

CREATE INDEX IF NOT EXISTS idx_products_status   ON products (status);
CREATE INDEX IF NOT EXISTS idx_products_category ON products (category);

-- 订单表
CREATE TABLE IF NOT EXISTS orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(50)  NOT NULL UNIQUE,       -- 订单号
    product_id    BIGINT       NOT NULL,
    product_title VARCHAR(100) NOT NULL,              -- 商品标题快照
    unit_price    INT          NOT NULL,              -- 成交单价快照，单位：分
    quantity      INT          NOT NULL DEFAULT 1,
    total_amount  INT          NOT NULL,              -- 总金额，单位：分
    buyer_name    VARCHAR(100),
    buyer_phone   VARCHAR(20),
    address       VARCHAR(500),
    status        VARCHAR(20)  NOT NULL DEFAULT 'created',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP,
    CONSTRAINT fk_orders_product      FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT chk_orders_unit_price  CHECK (unit_price >= 0),
    CONSTRAINT chk_orders_quantity    CHECK (quantity > 0),
    CONSTRAINT chk_orders_total       CHECK (total_amount >= 0)
);