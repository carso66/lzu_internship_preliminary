-- =====================================================================
-- 校园好物市集 schema.sql（H2 2.x 语法）
-- 约定：
--   1. 金额单位均为"分"，BIGINT 整数存储，禁止浮点
--   2. 全部使用 IF NOT EXISTS，脚本可重复执行，不清空已有数据
--   3. 金额溢出处理见文末注释块
-- =====================================================================

-- 商品表
CREATE TABLE IF NOT EXISTS products (
                                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        title       VARCHAR(100)  NOT NULL,
    price       BIGINT        NOT NULL,
    stock       INT           NOT NULL DEFAULT 0,
    category    VARCHAR(32)   NOT NULL,
    description VARCHAR(1000),
    -- 上下架状态；并发扣库存统一约定（把"已上架"检查并入原子 UPDATE，防止校验-扣减间隙被下架）：
    --   UPDATE products SET stock = stock - ? WHERE id = ? AND stock >= ? AND status = 'on'
    status      VARCHAR(4)    NOT NULL DEFAULT 'on',
    seller_name VARCHAR(64)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_products_price CHECK (price > 0),
    CONSTRAINT chk_products_stock  CHECK (stock >= 0),
    CONSTRAINT chk_products_status CHECK (status IN ('on', 'off'))
    );

-- 订单表（保存商品标题/单价快照，价格与金额一律由服务端计算）
CREATE TABLE IF NOT EXISTS orders (
                                      id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      order_no      VARCHAR(32)  NOT NULL,
    product_id    BIGINT       NOT NULL,
    product_title VARCHAR(100) NOT NULL,
    quantity      INT          NOT NULL,
    unit_price    BIGINT       NOT NULL,
    total_amount  BIGINT       NOT NULL,
    buyer_name    VARCHAR(64)  NOT NULL,
    buyer_phone   VARCHAR(20)  NOT NULL,
    address       VARCHAR(200) NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'created',
    paid_at       TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_orders_order_no    UNIQUE (order_no),
    CONSTRAINT fk_orders_product     FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT chk_orders_quantity   CHECK (quantity >= 1),
    CONSTRAINT chk_orders_unit_price CHECK (unit_price > 0),
    CONSTRAINT chk_orders_amount     CHECK (total_amount >= 0),
    CONSTRAINT chk_orders_amount_calc CHECK (total_amount = unit_price * quantity),
    CONSTRAINT chk_orders_status     CHECK (status IN ('created', 'paid'))
    );

-- L1-8：按手机号查订单、按创建时间倒序（等值列在前，排序列在后）
CREATE INDEX IF NOT EXISTS idx_orders_buyer_phone_created_at
    ON orders (buyer_phone, created_at);

