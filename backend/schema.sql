-- ============================================================================
-- 校园好物市集 · 数据库建表脚本
--
-- 依据：
--   1. 官方 README 第 4 节 L0-1 给出的字段示例；
--   2. 现有领域模型 Product / Order、DTO 校验约束、JdbcProductRepository /
--      JdbcOrderRepository 中的表结构说明，三者严格对齐。
--
-- 约定：
--   * 金额字段 price / unit_price / total_amount 一律用 BIGINT，以「分」为单位的
--     整数存储，全程不使用浮点数（README 第 3 节）。
--   * 所有 SQL 使用 CREATE TABLE/INDEX IF NOT EXISTS，保证脚本幂等：多个 Spring
--     测试上下文（@SpringBootTest）共享同一个 H2 内存库时，重复执行本脚本不会
--     报「表已存在」，因此无需开启 continue-on-error 去吞掉真实错误。
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 商品表 products
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS products (
    -- 自增主键，应用插入时省略，由数据库生成，回填到领域模型
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 标题，非空，长度与 ProductCreateRequest 的 @Size(max=100) 一致
    title       VARCHAR(100)  NOT NULL,
    -- 价格（分），非空，非负，对应 @Min(0)
    price       BIGINT        NOT NULL,
    -- 库存数量，非空，非负（下单扣减后不得为负数），对应 @Min(0)
    stock       INTEGER       NOT NULL,
    -- 分类，非空，与 @Size(max=50) 一致
    category    VARCHAR(50)   NOT NULL,
    -- 备注，可空，与 @Size(max=500) 一致
    description VARCHAR(500),
    -- 状态 on/off，非空，默认 on（与 ProductServiceImpl 的默认值一致）
    status      VARCHAR(10)   NOT NULL DEFAULT 'on',
    -- 卖家名称，非空，与 @Size(max=50) 一致
    seller_name VARCHAR(50)   NOT NULL,
    -- 创建时间，由 Service 层写入（LocalDateTime.now()），非空
    created_at  TIMESTAMP     NOT NULL,
    -- 在应用校验之外，由数据库约束保证库存、价格和状态的取值范围。
    CONSTRAINT ck_products_price_non_negative CHECK (price >= 0),
    CONSTRAINT ck_products_stock_non_negative CHECK (stock >= 0),
    CONSTRAINT ck_products_status CHECK (status IN ('on', 'off'))
);

-- ----------------------------------------------------------------------------
-- 订单表 orders
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
    -- 自增主键，订单号由该主键派生（见 OrderNoGenerator）
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 订单号，非空，唯一。
    -- 长度说明：下单时先用临时占位号 "P" + 32 位十六进制 UUID = 33 字符，再回填
    -- 正式编号 "SO" + 8 位日期 + 自增序号（约 16~29 字符）。二者均 ≤ 48，故取
    -- VARCHAR(48)；不得收窄到 VARCHAR(32)，否则 33 字符占位号会被拒绝。
    order_no      VARCHAR(48)   NOT NULL,
    -- 商品 ID，非空，外键指向 products.id（保证引用完整性）
    product_id    BIGINT        NOT NULL,
    -- 商品标题快照，下单时由服务端拷贝，避免商品后续改名影响历史订单
    product_title VARCHAR(100)  NOT NULL,
    -- 购买数量，非空，必须为正数（quantity > 0，对应 @Min(1)）
    quantity      INTEGER       NOT NULL,
    -- 下单时单价（分），服务端从商品表读取，非空，非负
    unit_price    BIGINT        NOT NULL,
    -- 订单总额（分）= unit_price × quantity，服务端计算，非空，非负
    total_amount  BIGINT        NOT NULL,
    -- 买家姓名，非空，与 @Size(max=50) 一致
    buyer_name    VARCHAR(50)   NOT NULL,
    -- 买家手机号，非空，与 @Size(max=20) 一致（L1-8 列表按此过滤）
    buyer_phone   VARCHAR(20)   NOT NULL,
    -- 收货地址，非空，与 @Size(max=200) 一致
    address       VARCHAR(200)  NOT NULL,
    -- 状态 created/paid，非空，默认 created
    status        VARCHAR(10)   NOT NULL DEFAULT 'created',
    -- 创建时间，由 Service 层写入，非空
    created_at    TIMESTAMP     NOT NULL,
    -- 预留的支付时间，创建订单时留空
    paid_at       TIMESTAMP,
    -- 订单号唯一，金额与数量受 CHECK 限制，商品引用由外键保证。
    CONSTRAINT uq_orders_order_no UNIQUE (order_no),
    CONSTRAINT ck_orders_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_orders_unit_price_non_negative CHECK (unit_price >= 0),
    CONSTRAINT ck_orders_total_amount_non_negative CHECK (total_amount >= 0),
    CONSTRAINT ck_orders_status CHECK (status IN ('created', 'paid')),
    CONSTRAINT fk_orders_product FOREIGN KEY (product_id) REFERENCES products (id)
);

-- ----------------------------------------------------------------------------
-- 索引（按实际查询需求，避免过度设计）
-- ----------------------------------------------------------------------------
-- L1-8 订单列表：WHERE buyer_phone = ? ORDER BY created_at DESC, id DESC
-- 对 buyer_phone 建索引，支撑按手机号过滤 + 分页的等值查询。
-- order_no 上的唯一约束已隐式建索引，无需重复创建。
CREATE INDEX IF NOT EXISTS idx_orders_buyer_phone ON orders (buyer_phone);
