-- 商品表：价格使用整数分；文本长度是本项目自行制定的限制。
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    price BIGINT NOT NULL,
    stock INTEGER NOT NULL,
    category VARCHAR(60) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    status VARCHAR(10) NOT NULL DEFAULT 'on',
    seller_name VARCHAR(60) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 数据库约束是最后一道防线，接口层仍需提前校验并返回清楚的错误信息。
    CONSTRAINT ck_products_price CHECK (price > 0),
    CONSTRAINT ck_products_stock CHECK (stock >= 0),
    CONSTRAINT ck_products_status CHECK (status IN ('on', 'off'))
);

-- 订单表：单独保存购买时的标题和单价，后续商品变化不会改写历史订单。
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    product_id BIGINT NOT NULL,
    product_title VARCHAR(120) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price BIGINT NOT NULL,
    total_amount BIGINT NOT NULL,
    buyer_name VARCHAR(60) NOT NULL,
    buyer_phone VARCHAR(20) NOT NULL,
    address VARCHAR(500) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'created',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMP,
    -- 唯一约束防止订单号重复，外键保证订单关联的商品存在。
    CONSTRAINT uq_orders_order_no UNIQUE (order_no),
    CONSTRAINT fk_orders_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_orders_quantity CHECK (quantity >= 1),
    CONSTRAINT ck_orders_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_orders_total_amount CHECK (total_amount > 0),
    CONSTRAINT ck_orders_status CHECK (status IN ('created', 'paid'))
);

-- 每个订单最多一条成功支付记录；金额从订单快照读取。
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(64) NOT NULL UNIQUE,
    order_no VARCHAR(64) NOT NULL UNIQUE REFERENCES orders(order_no),
    method VARCHAR(10) NOT NULL CHECK (method IN ('alipay', 'wechat')),
    amount BIGINT NOT NULL CHECK (amount > 0),
    status VARCHAR(10) NOT NULL DEFAULT 'paid' CHECK (status = 'paid'),
    paid_at TIMESTAMP NOT NULL
);
