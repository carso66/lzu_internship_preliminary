-- 校园好物市集 · 建表脚本
-- 金额统一用「分」(INT)，全程整数运算，不出现浮点

DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;

CREATE TABLE products (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(100) NOT NULL,
    price       INT          NOT NULL,
    stock       INT          NOT NULL DEFAULT 0,
    category    VARCHAR(50)  NOT NULL,
    description VARCHAR(1000),
    status      VARCHAR(8)   NOT NULL DEFAULT 'on',
    seller_name VARCHAR(50)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_products_price  CHECK (price >= 0),
    CONSTRAINT ck_products_stock  CHECK (stock >= 0),
    CONSTRAINT ck_products_status CHECK (status IN ('on', 'off'))
);

-- 列表默认按 创建时间倒序 + 可按 status 过滤
CREATE INDEX idx_products_status_created ON products (status, created_at DESC);
CREATE INDEX idx_products_category       ON products (category);

CREATE TABLE orders (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(32)  NOT NULL,
    product_id    BIGINT       NOT NULL,
    product_title VARCHAR(100) NOT NULL,
    quantity      INT          NOT NULL,
    unit_price    INT          NOT NULL,
    total_amount  BIGINT       NOT NULL,   -- 冗余存下单时的价格快照，订单是历史凭据
    buyer_name    VARCHAR(50)  NOT NULL,
    buyer_phone   VARCHAR(20)  NOT NULL,
    address       VARCHAR(255) NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'created',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP,
    CONSTRAINT uk_orders_order_no UNIQUE (order_no),
    CONSTRAINT ck_orders_quantity CHECK (quantity >= 1),
    CONSTRAINT ck_orders_status   CHECK (status IN ('created', 'paid'))
);

-- 订单列表主查询：buyer_phone 等值 + created_at 倒序
-- 复合索引的列顺序 = 等值列在前、排序列在后
CREATE INDEX idx_orders_buyer_created ON orders (buyer_phone, created_at DESC);

CREATE TABLE payments (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_no VARCHAR(32) NOT NULL,
    order_id   BIGINT      NOT NULL,
    method     VARCHAR(16) NOT NULL,
    amount     BIGINT      NOT NULL,   -- 与 orders.total_amount 同类型，避免两边对不上
    status     VARCHAR(16) NOT NULL DEFAULT 'paid',
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at    TIMESTAMP,
    CONSTRAINT uk_payments_payment_no UNIQUE (payment_no),
    CONSTRAINT uk_payments_order_id   UNIQUE (order_id),   -- 幂等的最后一道闸
    CONSTRAINT ck_payments_method     CHECK (method IN ('alipay', 'wechat'))
);
