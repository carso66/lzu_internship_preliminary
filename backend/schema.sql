-- 校园好物市集 · 建表脚本（H2 兼容）
-- 由 Spring Boot 启动时经 spring.sql.init 自动执行；IF NOT EXISTS 保证可重复执行。

CREATE TABLE IF NOT EXISTS products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(100) NOT NULL,
    price       BIGINT       NOT NULL CHECK (price >= 0),        -- 单位：分
    stock       INT          NOT NULL CHECK (stock >= 0),
    category    VARCHAR(50)  NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    status      VARCHAR(8)   NOT NULL DEFAULT 'on' CHECK (status IN ('on', 'off')),
    seller_name VARCHAR(50)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(32)  NOT NULL,
    product_id    BIGINT       NOT NULL,
    product_title VARCHAR(100) NOT NULL,                         -- 下单快照
    quantity      INT          NOT NULL CHECK (quantity >= 1),
    unit_price    BIGINT       NOT NULL CHECK (unit_price >= 0), -- 成交单价快照（分）
    total_amount  BIGINT       NOT NULL CHECK (total_amount >= 0),
    buyer_name    VARCHAR(50)  NOT NULL,
    buyer_phone   VARCHAR(20)  NOT NULL,
    address       VARCHAR(200) NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'paid')),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP    NULL,                             -- 未支付为 NULL
    CONSTRAINT uk_orders_order_no UNIQUE (order_no),
    CONSTRAINT fk_orders_product  FOREIGN KEY (product_id) REFERENCES products (id)
);
