-- 商品表
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    price BIGINT NOT NULL,                    -- 单位：分
    stock INT NOT NULL,
    category VARCHAR(50) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    image_url VARCHAR(500) NOT NULL DEFAULT '',
    status VARCHAR(10) NOT NULL DEFAULT 'on',
    seller_name VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_stock CHECK (stock >= 0),
    CONSTRAINT ck_products_status CHECK (status IN ('on', 'off'))
);


-- 订单表
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    product_id BIGINT NOT NULL,
    product_title VARCHAR(100) NOT NULL,
    quantity INT NOT NULL,
    unit_price BIGINT NOT NULL,               -- 单位：分（下单时的商品快照价）
    total_amount BIGINT NOT NULL,             -- 单位：分
    buyer_name VARCHAR(50) NOT NULL,
    buyer_phone VARCHAR(20) NOT NULL,
    address VARCHAR(500) NOT NULL,
    remark VARCHAR(500) NOT NULL DEFAULT '',
    status VARCHAR(10) NOT NULL DEFAULT 'created',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMP,

    CONSTRAINT uk_orders_order_no UNIQUE (order_no),
    CONSTRAINT fk_orders_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT ck_orders_quantity CHECK (quantity >= 1),
    CONSTRAINT ck_orders_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_orders_total_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_orders_amount_match CHECK (total_amount = unit_price * CAST(quantity AS BIGINT)),
    CONSTRAINT ck_orders_status CHECK (status IN ('created', 'paid'))
);
CREATE INDEX IF NOT EXISTS idx_products_status
    ON products(status);

CREATE INDEX IF NOT EXISTS idx_products_category
    ON products(category);

CREATE INDEX IF NOT EXISTS idx_orders_phone_created
    ON orders(buyer_phone, created_at DESC, id DESC);
