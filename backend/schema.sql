-- ============================================================
-- 校园好物市集 · 数据库结构
--
-- 四个设计决定，解释见 DESIGN.md：
--   1. 金额一律用 INT 存「分」，不用浮点、不用 DECIMAL。1990 表示 19.90 元。
--   2. orders 冗余 product_title / unit_price，是下单那一刻的快照：
--      商品后来改价，历史订单金额不能被改。
--   3. payments.order_no 加唯一约束，从数据库层面挡住同一订单重复支付。
--   4. 每次启动重建表（DROP + CREATE），保证评审拿到的初始数据和我这里一致。
-- ============================================================

DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;

-- ---------- 商品 ----------
CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(100) NOT NULL,
    price       INT          NOT NULL,                -- 单位：分
    stock       INT          NOT NULL DEFAULT 0,
    category    VARCHAR(50),
    description VARCHAR(500),
    status      VARCHAR(10)  NOT NULL DEFAULT 'on',   -- on 上架 / off 下架
    seller_name VARCHAR(50),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- 订单 ----------
CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(32)  NOT NULL,              -- 业务单号，唯一
    product_id    BIGINT       NOT NULL,
    product_title VARCHAR(100) NOT NULL,              -- 快照
    quantity      INT          NOT NULL,
    unit_price    INT          NOT NULL,              -- 快照，单位：分
    total_amount  INT          NOT NULL,              -- unit_price * quantity
    buyer_name    VARCHAR(50)  NOT NULL,
    buyer_phone   VARCHAR(20)  NOT NULL,
    address       VARCHAR(200),
    status        VARCHAR(20)  NOT NULL DEFAULT 'created',  -- created / paid
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP,
    CONSTRAINT uk_orders_order_no UNIQUE (order_no)
);

-- ---------- 支付流水 ----------
CREATE TABLE payments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(32) NOT NULL,
    order_no   VARCHAR(32) NOT NULL,
    amount     INT         NOT NULL,
    method     VARCHAR(20) NOT NULL,                  -- alipay / wechat
    status     VARCHAR(20) NOT NULL,                  -- paid
    paid_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_payments_payment_id UNIQUE (payment_id),
    CONSTRAINT uk_payments_order_no   UNIQUE (order_no)   -- 幂等的兜底
);

-- ---------- 索引 ----------
-- 商品列表最常用的两种过滤：按状态、按分类
CREATE INDEX idx_products_status   ON products (status);
CREATE INDEX idx_products_category ON products (category);

-- 订单按买家手机号查列表
CREATE INDEX idx_orders_buyer_phone ON orders (buyer_phone);
