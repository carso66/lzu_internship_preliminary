#!/usr/bin/env bash
# EXPLAIN before/after comparison for idx_orders_buyer_created.
#
# What it does:
#   1. picks an H2 jar (env H2_JAR, else Maven local repo)
#   2. builds a throwaway file database with the same orders DDL as schema.sql
#   3. inserts 5000 rows (50 buyers x 100 orders each)
#   4. runs EXPLAIN ANALYZE on the orders-list query WITHOUT the index
#   5. creates the index, runs the same EXPLAIN ANALYZE again
#   6. compares rows read (scanCount) and the access path
#   6. deletes the throwaway database
#
# Usage:  bash backend/scripts/explain_index.sh
# Output is ASCII only so it prints cleanly in any terminal.

set -u

ROWS=${ROWS:-5000}
BUYERS=${BUYERS:-50}

die() { echo "ERROR: $*" >&2; exit 1; }

# ---------- locate h2 jar ----------
find_h2() {
    if [ -n "${H2_JAR:-}" ] && [ -f "${H2_JAR}" ]; then echo "${H2_JAR}"; return; fi
    local roots=()
    [ -d "${HOME}/.m2/repository/com/h2database" ] && roots+=("${HOME}/.m2/repository/com/h2database")
    [ -d "D:/maven-repo/com/h2database" ] && roots+=("D:/maven-repo/com/h2database")
    [ -d "/d/maven-repo/com/h2database" ] && roots+=("/d/maven-repo/com/h2database")
    local r
    for r in "${roots[@]}"; do
        local hit
        hit=$(find "$r" -name 'h2-*.jar' ! -name '*-sources.jar' ! -name '*-javadoc.jar' 2>/dev/null | sort | tail -1)
        if [ -n "$hit" ]; then echo "$hit"; return; fi
    done
}

H2_JAR=$(find_h2)
[ -n "${H2_JAR}" ] || die "h2 jar not found. Run 'mvn -B dependency:resolve' first, or export H2_JAR=/path/to/h2-2.x.jar"
command -v java >/dev/null 2>&1 || die "java not on PATH"

WORK="$(mktemp -d 2>/dev/null || echo "${TEMP:-/tmp}/lzu-explain-$$")"
mkdir -p "$WORK"
DB_URL="jdbc:h2:file:${WORK}/explain;DB_CLOSE_DELAY=-1"
SQL_FILE="${WORK}/run.sql"
trap 'rm -rf "$WORK"' EXIT

echo "H2 jar : ${H2_JAR}"
echo "temp db: ${WORK}/explain.mv.db"
echo "dataset: ${ROWS} rows, ${BUYERS} distinct buyer_phone"
echo

run_sql() {
    java -cp "$H2_JAR" org.h2.tools.Shell \
        -url "$DB_URL" -user sa -password "" -sql "$1" 2>&1
}

# ---------- schema + data (no index yet) ----------
cat > "$SQL_FILE" <<SQL
CREATE TABLE orders (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(32)  NOT NULL,
    product_id    BIGINT       NOT NULL,
    product_title VARCHAR(100) NOT NULL,
    quantity      INT          NOT NULL,
    unit_price    INT          NOT NULL,
    total_amount  BIGINT       NOT NULL,
    buyer_name    VARCHAR(50)  NOT NULL,
    buyer_phone   VARCHAR(20)  NOT NULL,
    address       VARCHAR(255) NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'created',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at       TIMESTAMP,
    CONSTRAINT uk_orders_order_no UNIQUE (order_no),
    CONSTRAINT ck_orders_quantity CHECK (quantity >= 1),
    CONSTRAINT ck_orders_status   CHECK (status IN ('created', 'paid'))
);

INSERT INTO orders (order_no, product_id, product_title, quantity, unit_price,
                    total_amount, buyer_name, buyer_phone, address, status, created_at)
SELECT 'SO' || LPAD(CAST(X AS VARCHAR), 14, '0'), 1, 'Math Review Book', 1, 1990, 1990,
       'Buyer ' || CAST(MOD(X, ${BUYERS}) AS VARCHAR),
       '138' || LPAD(CAST(MOD(X, ${BUYERS}) AS VARCHAR), 8, '0'),
       'Lanzhou University', 'created',
       TIMESTAMP '2026-11-01 00:00:00' + (X * INTERVAL '1' SECOND)
FROM SYSTEM_RANGE(1, ${ROWS});

SELECT COUNT(*) AS orders_rows FROM orders;
SELECT COUNT(DISTINCT buyer_phone) AS distinct_buyers FROM orders;
SQL

echo "===== step 1: schema + ${ROWS} rows ====="
run_sql "$(cat "$SQL_FILE")" | grep -Ei 'orders_rows|distinct_buyers|^[0-9]+$|ERROR' || true
echo

QUERY="SELECT id, order_no, product_id, product_title, quantity, unit_price, total_amount,
              buyer_name, buyer_phone, address, status, created_at, paid_at
       FROM orders
       WHERE buyer_phone = '13800000007'
       ORDER BY created_at DESC, id DESC
       LIMIT 10 OFFSET 0"

echo "===== step 2: EXPLAIN ANALYZE without index ====="
BEFORE=$(run_sql "EXPLAIN ANALYZE $QUERY")
echo "$BEFORE"
echo

echo "===== step 3: CREATE INDEX idx_orders_buyer_created ====="
run_sql "CREATE INDEX idx_orders_buyer_created ON orders (buyer_phone, created_at DESC);" || die "create index failed"
echo "index created"
echo

echo "===== step 4: EXPLAIN ANALYZE with index ====="
AFTER=$(run_sql "EXPLAIN ANALYZE $QUERY")
echo "$AFTER"
echo

# ---------- verdict ----------
echo "===== verdict ====="
scan_of() { echo "$1" | grep -o 'scanCount: [0-9]*' | tail -1 | grep -o '[0-9]*'; }

B_SCAN=$(scan_of "$BEFORE")
A_SCAN=$(scan_of "$AFTER")
b_tab=no; a_idx=no
echo "$BEFORE" | grep -qi 'tableScan'                 && b_tab=yes
echo "$AFTER"  | grep -qi 'idx_orders_buyer_created'  && a_idx=yes

echo "before index : path=tableScan? $b_tab  rows_read=${B_SCAN:-?}"
echo "after  index : path=uses_idx? $a_idx  rows_read=${A_SCAN:-?}"
echo

ok=yes
[ "$b_tab" = yes ] || ok=no
[ "$a_idx" = yes ] || ok=no
if [ -n "$B_SCAN" ] && [ -n "$A_SCAN" ]; then
    [ "$A_SCAN" -lt "$B_SCAN" ] || ok=no
else
    ok=no
fi

if [ "$ok" = yes ]; then
    echo "RESULT: INDEX USED, ROWS READ ${B_SCAN} -> ${A_SCAN}"
    exit 0
fi
echo "RESULT: UNEXPECTED PLAN - review the output above"
exit 1
